// incepator = alb, intermediar = gri deschis, mixt = gri, avansat = negru.

let _sid = 0
function c(
  day: ScheduleClass['day'],
  discipline: string,
  ageGroup: string,
  startTime: string,
  endTime: string,
  level: ScheduleClass['level'],
): ScheduleClass {
  return { id: `cls-${++_sid}`, day, discipline, ageGroup, startTime, endTime, level }
}

